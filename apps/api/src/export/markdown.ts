import type { HandoverDetail } from '@relay/contracts';

export interface ExportMetadata {
  exportedAt: string;
}

/**
 * Escapes both HTML and Markdown syntax characters to prevent:
 * - HTML injection (<script>, <iframe>, <img>)
 * - Active Markdown links ([click](url))
 * - Unintended table/layout breakage (|)
 * URLs are converted to inert plain text.
 */
export function escapeMarkdown(str: string): string {
  if (!str) return '';
  // 1. Defang HTML syntax
  const htmlSafe = str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');

  // 2. Escape Markdown control characters
  return htmlSafe.replace(/([\\`*_{}[\]()#+\-.!|~])/g, '\\$1');
}

/**
 * Capitalizes string to title case for labels.
 */
function toLabelCase(str: string): string {
  if (!str) return '';
  return str
    .split('_')
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase())
    .join(' ');
}

export function renderHandoverMarkdown(handover: HandoverDetail, metadata: ExportMetadata): string {
  const lines: string[] = [];

  const title = escapeMarkdown(handover.title || handover.configuration.title);
  const version = handover.version;
  const status = escapeMarkdown(toLabelCase(handover.status));
  const recipient = escapeMarkdown(handover.recipientName || 'Incoming Team Member');
  const approver = escapeMarkdown(handover.approvedBy || 'Authorised Reviewer');
  const approvedAt = handover.approvedAt
    ? escapeMarkdown(new Date(handover.approvedAt).toUTCString())
    : 'Not Recorded';
  const exportedAt = escapeMarkdown(new Date(metadata.exportedAt).toUTCString());

  // ─── Header ────────────────────────────────────────────────────────────────
  lines.push(`# ${title}`);
  lines.push('');
  lines.push(`- **Version**: v${version}`);
  lines.push(`- **Status**: ${status}`);
  lines.push(`- **Recipient**: ${recipient}`);
  lines.push(`- **Approver**: ${approver}`);
  lines.push(`- **Approved At**: ${approvedAt}`);
  lines.push(`- **Exported At**: ${exportedAt}`);
  if (handover.configuration.priorityFocus) {
    lines.push(
      `- **Priority Focus Preference**: ${escapeMarkdown(handover.configuration.priorityFocus)}`
    );
  }
  lines.push('');

  // ─── Filter Non-rejected Items ─────────────────────────────────────────────
  const nonRejectedItems = (handover.items || []).filter((i) => i.reviewState !== 'rejected');

  // Group items by configured sections
  const sectionKeys = handover.configuration.includedSections || [];
  const itemsBySection = new Map<string, typeof nonRejectedItems>();
  for (const sk of sectionKeys) {
    itemsBySection.set(sk, []);
  }
  for (const item of nonRejectedItems) {
    const list = itemsBySection.get(item.section) || [];
    list.push(item);
    itemsBySection.set(item.section, list);
  }

  // ─── Table of Contents ─────────────────────────────────────────────────────
  lines.push('## Contents');
  lines.push('');
  let secIdx = 1;
  for (const secKey of sectionKeys) {
    const secItems = itemsBySection.get(secKey) || [];
    lines.push(`${secIdx}. ${escapeMarkdown(toLabelCase(secKey))} (${secItems.length} items)`);
    secIdx++;
  }
  lines.push('');

  // ─── Sections & Items ──────────────────────────────────────────────────────
  secIdx = 1;
  for (const secKey of sectionKeys) {
    const secItems = itemsBySection.get(secKey) || [];
    lines.push(`## ${secIdx}. ${escapeMarkdown(toLabelCase(secKey))}`);
    lines.push('');

    if (secItems.length === 0) {
      lines.push('*No items recorded in this section.*');
      lines.push('');
      secIdx++;
      continue;
    }

    let itemNum = 1;
    for (const item of secItems) {
      const kindLabel = toLabelCase(item.itemKind);
      const evidenceLabel = toLabelCase(item.evidenceState);

      lines.push(`### ${secIdx}.${itemNum} [${kindLabel} | ${evidenceLabel}]`);
      lines.push('');
      lines.push(escapeMarkdown(item.text));
      lines.push('');

      if (item.originalText && item.editedBy) {
        lines.push('*Edited by reviewer; wording not machine-verified.*');
        lines.push('');
      }

      if (item.citations && item.citations.length > 0) {
        lines.push('**Evidence:**');
        for (const cit of item.citations) {
          const source = escapeMarkdown(cit.sourceTitle || 'Project Source');
          const ref = cit.quote ? `Quote: "${escapeMarkdown(cit.quote)}"` : 'Quote not recorded';
          lines.push(`- ${source} — ${ref}`);
        }
        lines.push('');
      }

      itemNum++;
    }

    secIdx++;
  }

  // ─── Footer ────────────────────────────────────────────────────────────────
  lines.push('---');
  lines.push(
    `*Generated by Prasaranam Knowledge Handover Platform on ${exportedAt}. Document contains only authorised project knowledge verified for the named recipient.*`
  );
  lines.push('');

  return lines.join('\n');
}
